#!/usr/bin/env python3
"""Renders docs/privacy-policy.md as the static, self-contained docs/privacy-policy.html.

Handles only what that file uses: headings, paragraphs, bullet lists, a leading blockquote (the
draft note), **bold**, `code` and links. [[PLACEHOLDER: ...]] text is highlighted. Run it after
every edit to the Markdown:

    python3 scripts/render-privacy-policy.py
"""
import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs" / "privacy-policy.md"
TARGET = ROOT / "docs" / "privacy-policy.html"


def inline(text: str) -> str:
    text = html.escape(text, quote=False)
    text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', text)
    return re.sub(r"(\[\[PLACEHOLDER:.*?\]\])", r"<mark>\1</mark>", text)


def render(markdown: str) -> str:
    out, paragraph, quote, items = [], [], [], []

    def flush():
        if paragraph:
            out.append("<p>" + inline(" ".join(paragraph)) + "</p>")
            paragraph.clear()
        if quote:
            out.append('<div class="draft" role="note">' + inline(" ".join(quote)) + "</div>")
            quote.clear()
        if items:
            out.append("<ul>\n" + "\n".join("<li>" + inline(i) + "</li>" for i in items) + "\n</ul>")
            items.clear()

    for line in markdown.splitlines():
        if line.startswith("> "):
            quote.append(line[2:].strip())
        elif line.startswith("# "):
            flush()
            out.append("<h1>" + inline(line[2:]) + "</h1>")
        elif line.startswith("## "):
            flush()
            out.append("<h2>" + inline(line[3:]) + "</h2>")
        elif line.startswith("- "):
            if paragraph or quote:
                flush()
            items.append(line[2:].strip())
        elif line.startswith("  ") and items and line.strip():
            items[-1] += " " + line.strip()
        elif not line.strip():
            flush()
        else:
            paragraph.append(line.strip())
    flush()
    return "\n".join(out)


PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
__ROBOTS__
<title>Bukin Mic Recorder - Privacy policy</title>
<!-- Generated by scripts/render-privacy-policy.py from docs/privacy-policy.md: edit the Markdown,
     then regenerate. Draft pages are noindex; publication requires owner approval. -->
<style>
  :root { color-scheme: light dark; --fg: #1b1c1f; --bg: #f7f8fa; --accent: #2c5f9e; --mark: #fff3b0; }
  @media (prefers-color-scheme: dark) { :root { --fg: #e3e4e8; --bg: #15171b; --accent: #9cc2f5; --mark: #5c4d00; } }
  body { margin: 0; padding: 24px 16px 48px; background: var(--bg); color: var(--fg);
         font: 16px/1.6 system-ui, -apple-system, "Segoe UI", Roboto, sans-serif; }
  main { max-width: 720px; margin: 0 auto; }
  h1 { font-size: 1.8rem; margin: 0 0 1rem; }
  h2 { font-size: 1.2rem; margin: 2rem 0 .5rem; }
  a { color: var(--accent); }
  code { font-size: .9em; overflow-wrap: anywhere; }
  mark { background: var(--mark); color: inherit; }
  .draft { border: 2px solid #c62828; border-radius: 8px; padding: 12px 16px; margin: 0 0 1.5rem; }
  ul { padding-left: 1.25rem; }
</style>
</head>
<body>
<main>
%s
</main>
</body>
</html>
"""

def render_page(markdown: str) -> str:
    draft = "[[PLACEHOLDER" in markdown or bool(re.search(r"\bDRAFT\b", markdown, re.I))
    robots = '<meta name="robots" content="noindex">' if draft else ""
    return PAGE.replace("__ROBOTS__", robots) % render(markdown)


if __name__ == "__main__":
    TARGET.write_text(render_page(SOURCE.read_text(encoding="utf-8")), encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
